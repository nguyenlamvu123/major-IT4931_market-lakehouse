"""Generate Strimzi ``KafkaTopic`` CRs from ``contracts/topics.yaml``.

The output (``infra/k8s/kafka/topics.yaml``) is committed so ``kustomize build`` needs no
Python, and a test fails if it drifts from the contract. Regenerate after editing the
contract:

    python -m infra.scripts.gen_kafka_topics                 # dev: replicas 1
    python -m infra.scripts.gen_kafka_topics --replicas 3 --min-insync 2 --output -   # demo
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from infra.scripts.topics_contract import ROOT, TopicSpec, load_document, load_topics

OUTPUT = ROOT / "infra" / "k8s" / "kafka" / "topics.yaml"
HEADER = (
    "# GENERATED by `python -m infra.scripts.gen_kafka_topics` from contracts/topics.yaml.\n"
    "# Do not edit by hand: change the contract and regenerate.\n"
)


def topic_resource(topic: TopicSpec, replicas: int, min_insync: int) -> dict:
    return {
        "apiVersion": "kafka.strimzi.io/v1beta2",
        "kind": "KafkaTopic",
        "metadata": {
            # Topic names like "crypto.trades" are valid DNS-1123 subdomains, so the CR
            # name equals the topic name; spec.topicName makes that explicit anyway.
            "name": topic.name,
            "namespace": "kafka",
            "labels": {
                "strimzi.io/cluster": "market",
                "btl.market/producer": topic.producer,
            },
        },
        "spec": {
            "topicName": topic.name,
            "partitions": topic.partitions,
            "replicas": replicas,
            "config": {
                "retention.ms": topic.retention_ms,
                "cleanup.policy": load_document()["defaults"]["cleanup_policy"],
                "min.insync.replicas": min_insync,
            },
        },
    }


def render(replicas: int = 1, min_insync: int = 1) -> str:
    if min_insync > replicas:
        raise ValueError("min.insync.replicas cannot exceed replicas")
    documents = [topic_resource(topic, replicas, min_insync) for topic in load_topics()]
    body = yaml.safe_dump_all(documents, sort_keys=False, explicit_start=True)
    return HEADER + body


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Strimzi KafkaTopic CRs")
    parser.add_argument("--replicas", type=int, default=1)
    parser.add_argument("--min-insync", type=int, default=1)
    parser.add_argument("--output", default=str(OUTPUT), help="file path or - for stdout")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()

    text = render(args.replicas, args.min_insync)
    if args.check:
        current = Path(args.output).read_text(encoding="utf-8")
        if current != text:
            sys.exit(f"{args.output} is stale; run python -m infra.scripts.gen_kafka_topics")
        return
    if args.output == "-":
        sys.stdout.write(text)
        return
    Path(args.output).write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
